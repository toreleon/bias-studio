import { chromium, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import { createBetaStore } from '../server/beta-store.mjs';
import { createGenerationService } from '../server/beta-generation.mjs';
import { createDistributionService } from '../server/beta-distribution.mjs';
import { createBetaServer } from '../server/beta-server.mjs';

// Actual running UI + real local HTTP service. No provider simulation, credentials,
// Telegram requests or public network listener. Start Expo on 8081 with beta URL 8787.
const output = 'docs/screenshots/beta';
await mkdir(output,{recursive:true});
const store = createBetaStore({filename:':memory:'});
const invite = store.createInvite({label:'Luna Studio'});
const generation = createGenerationService({store,generate:async()=>{throw new Error('Generation disabled in screenshot session.');}});
const distribution = createDistributionService({store,publicBaseURL:'http://localhost:8787'});
const server = createBetaServer({store,generation,distribution});
await new Promise((resolve,reject)=>{server.once('error',reject);server.listen(8787,'127.0.0.1',resolve);});
const browser = await chromium.launch({executablePath:process.env.CHROMIUM_PATH,headless:true,args:['--no-sandbox']});
try {
  const context = await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:2});
  const page = await context.newPage();
  const button = name=>page.getByRole('button',{name,exact:true});
  const shot = async name=>{await page.evaluate(()=>document.fonts.ready);await page.screenshot({path:`${output}/${name}.png`});};
  await page.goto('http://localhost:8081');
  await expect(button('Start a reaction pack')).toBeVisible();
  await shot('01-home');
  await button('Try a 3-reaction demo').click();
  await button('Name & creator credit').click();
  await page.getByRole('textbox',{name:'Pack name',exact:true}).fill('Encore energy');
  await page.getByRole('textbox',{name:'Creator credit',exact:true}).fill('@luna-studio');
  await button('Close collection details').click();
  await button('Save to library').click();
  await button('Got it').click();
  await expect(button('Saved on this device')).toBeVisible();
  const local = await page.evaluate(()=>JSON.parse(localStorage.getItem('bias-studio.workspace.v2')));
  const packId=local.collections[0].id;
  await page.goto(`http://localhost:8081/pack/${packId}`);
  await expect(page.getByText('Encore energy',{exact:true})).toBeVisible();
  await shot('02-pack');
  await button('Refine 1').click();
  await page.getByRole('textbox',{name:'Sticker caption'}).fill('my whole heart');
  await expect(button('Saved on this device')).toBeVisible();
  await page.evaluate(()=>{const nodes=[...document.querySelectorAll('*')].filter(e=>e.scrollHeight>e.clientHeight+50);nodes.forEach(e=>e.scrollTop=0);});
  await shot('03-editor');
  await page.goto('http://localhost:8081/library');
  await expect(page.getByRole('textbox',{name:'Search reactions'})).toBeVisible();
  await shot('04-library');
  await page.goto(`http://localhost:8081/preview/${packId}`);
  await expect(page.getByText('Ready for the chat?')).toBeVisible();
  await shot('05-preview');
  await page.getByRole('textbox',{name:'Sharing creator invite'}).fill(invite.code);
  await button('Connect creator account').click();
  await button('Publish collection page…').click();
  await button('Publish finished collection').click();
  await expect(page.getByText('Your finished stickers, creator credit and account display name are public.',{exact:false})).toBeVisible();
  await button('Got it').click();
  const remote=distribution.list(invite.creator)[0];
  if(!remote?.published) throw new Error('Actual local publication did not complete.');
  const recipient = await browser.newContext({viewport:{width:390,height:844},deviceScaleFactor:2});
  const publicPage=await recipient.newPage();
  await publicPage.goto(remote.publicURL);
  await expect(publicPage.getByRole('heading',{name:'Encore energy'})).toBeVisible();
  await publicPage.screenshot({path:`${output}/06-public-pack.png`,fullPage:true});
  await publicPage.goto(`http://localhost:8081/receive/${remote.id}`);
  await publicPage.getByRole('button',{name:'Save pack to Bias Studio',exact:true}).click();
  await expect(publicPage.getByRole('button',{name:'Got it',exact:true})).toBeVisible();
  await publicPage.getByRole('button',{name:'Got it',exact:true}).click();
  await expect(publicPage.getByText('Ready for the chat?')).toBeVisible();
  const received=await publicPage.evaluate(()=>JSON.parse(localStorage.getItem('bias-studio.workspace.v2')));
  if(received.collections[0].items.length!==3 || received.collections[0].items.some(i=>i.design.originalSource || i.provenance)) throw new Error('Recipient privacy/import failed.');
  distribution.unpublish(invite.creator,remote.id);
  const revoked=await fetch(remote.publicURL);
  if(revoked.status!==404) throw new Error('Unpublish did not revoke anonymous access.');
  await page.goto('http://localhost:8081');
  await button('Create with AI').click();
  await button('Concert cat').click();
  await button('Choose a look').click();
  await expect(button('Generate one sample')).toBeVisible();
  await expect(button('Saved on this device')).toBeVisible();
  await page.evaluate(()=>{document.querySelectorAll('*').forEach(e=>{if(e.scrollHeight>e.clientHeight+50)e.scrollTop=0;});});
  await shot('07-ai-sample');
  await writeFile(`${output}/capture.json`,JSON.stringify({capturedAt:new Date().toISOString(),viewport:{width:390,height:844},device:'Chromium mobile viewport; not a physical device',backend:'Actual loopback HTTP with ephemeral SQLite; no mocked routes',generation:'Disabled; no provider call',telegram:'Disabled; no bot call',verified:['UI rendered and uploaded finished stickers','anonymous recipient imported actual server ZIP','private source/provenance absent','unpublish returned404']},null,2)+'\n');
  console.log('Seven actual mobile-browser screens captured; real local publication, anonymous import and revocation passed.');
} finally {
  await browser.close(); await new Promise(resolve=>server.close(resolve));
  await generation.close();store.close();
}
